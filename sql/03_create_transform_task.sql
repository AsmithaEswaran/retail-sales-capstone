USE DATABASE RETAIL_DB;
USE SCHEMA RAW;

CREATE OR REPLACE TASK TRANSFORM_SALES_TASK
    WAREHOUSE = PIPELINE_WH
    AFTER LOAD_SALES_TASK
AS
MERGE INTO SALES_CURATED T
USING (
    SELECT
        TRY_TO_NUMBER(ORDER_ID) AS ORDER_ID,
        TRY_TO_DATE(ORDER_DATE) AS ORDER_DATE,
        TRY_TO_NUMBER(CUSTOMER_ID) AS CUSTOMER_ID,
        TRIM(PRODUCT) AS PRODUCT,
        TRY_TO_NUMBER(QUANTITY) AS QUANTITY,
        TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) AS UNIT_PRICE,
        UPPER(TRIM(STATUS)) AS STATUS
    FROM SALES_RAW
    WHERE TRY_TO_NUMBER(ORDER_ID) IS NOT NULL
      AND TRY_TO_DATE(ORDER_DATE) IS NOT NULL
      AND TRY_TO_NUMBER(CUSTOMER_ID) IS NOT NULL
      AND NULLIF(TRIM(PRODUCT), '') IS NOT NULL
      AND TRY_TO_NUMBER(QUANTITY) > 0
      AND TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) >= 0
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY TRY_TO_NUMBER(ORDER_ID)
        ORDER BY LOADED_AT DESC,
                 SOURCE_FILE DESC,
                 SOURCE_ROW_NUMBER DESC
    ) = 1
) S
ON T.ORDER_ID = S.ORDER_ID

WHEN MATCHED THEN UPDATE SET
    T.ORDER_DATE = S.ORDER_DATE,
    T.CUSTOMER_ID = S.CUSTOMER_ID,
    T.PRODUCT = S.PRODUCT,
    T.QUANTITY = S.QUANTITY,
    T.UNIT_PRICE = S.UNIT_PRICE,
    T.TOTAL_AMOUNT = S.QUANTITY * S.UNIT_PRICE,
    T.STATUS = S.STATUS,
    T.UPDATED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ

WHEN NOT MATCHED THEN INSERT (
    ORDER_ID, ORDER_DATE, CUSTOMER_ID, PRODUCT,
    QUANTITY, UNIT_PRICE, TOTAL_AMOUNT, STATUS, UPDATED_AT
)
VALUES (
    S.ORDER_ID, S.ORDER_DATE, S.CUSTOMER_ID, S.PRODUCT,
    S.QUANTITY, S.UNIT_PRICE, S.QUANTITY * S.UNIT_PRICE,
    S.STATUS, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
);