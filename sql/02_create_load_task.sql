USE DATABASE RETAIL_DB;
USE SCHEMA RAW;


ALTER TASK LOAD_SALES_TASK SUSPEND;
ALTER TASK IF EXISTS RETAIL_DB.RAW.TRANSFORM_SALES_TASK SUSPEND;

CREATE OR REPLACE TASK LOAD_SALES_TASK
    WAREHOUSE = PIPELINE_WH
    SCHEDULE = '5 MINUTES'
AS
COPY INTO SALES_RAW (
    ORDER_ID,
    ORDER_DATE,
    CUSTOMER_ID,
    PRODUCT,
    QUANTITY,
    UNIT_PRICE,
    STATUS,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    LOADED_AT
)
FROM (
    SELECT
        $1::VARCHAR,
        $2::VARCHAR,
        $3::VARCHAR,
        $4::VARCHAR,
        $5::VARCHAR,
        $6::VARCHAR,
        $7::VARCHAR,
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER,
        CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    FROM @SALES_STAGE
)
FILE_FORMAT = (FORMAT_NAME = SALES_CSV_FORMAT)
ON_ERROR = 'CONTINUE';

