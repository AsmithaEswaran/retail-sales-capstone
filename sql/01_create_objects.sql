USE DATABASE RETAIL_DB;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS SALES_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS SALES_STAGE
    FILE_FORMAT = SALES_CSV_FORMAT;

CREATE TABLE IF NOT EXISTS SALES_RAW (
    ORDER_ID VARCHAR,
    ORDER_DATE VARCHAR,
    CUSTOMER_ID VARCHAR,
    PRODUCT VARCHAR,
    QUANTITY VARCHAR,
    UNIT_PRICE VARCHAR,
    STATUS VARCHAR,
    SOURCE_FILE VARCHAR,
    SOURCE_ROW_NUMBER NUMBER,
    LOADED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS SALES_CURATED (
    ORDER_ID NUMBER,
    ORDER_DATE DATE,
    CUSTOMER_ID NUMBER,
    PRODUCT VARCHAR,
    QUANTITY NUMBER,
    UNIT_PRICE NUMBER(12,2),
    TOTAL_AMOUNT NUMBER(14,2),
    STATUS VARCHAR,
    UPDATED_AT TIMESTAMP_NTZ
);