-- Raw records
SELECT COUNT(*) AS RAW_COUNT
FROM RETAIL_DB.RAW.SALES_RAW;

-- Curated records
SELECT *
FROM RETAIL_DB.RAW.SALES_CURATED
ORDER BY ORDER_ID;

-- Sales by product, excluding cancelled orders
SELECT
    PRODUCT,
    SUM(QUANTITY) AS UNITS_SOLD,
    SUM(TOTAL_AMOUNT) AS TOTAL_SALES
FROM RETAIL_DB.RAW.SALES_CURATED
WHERE STATUS = 'COMPLETED'
GROUP BY PRODUCT
ORDER BY TOTAL_SALES DESC;

-- Duplicate check: expected to return zero rows
SELECT ORDER_ID, COUNT(*) AS CNT
FROM RETAIL_DB.RAW.SALES_CURATED
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;